'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const examplesDir = path.join(root, 'Examples');
const outPath = path.join(root, 'js', 'examples-data.js');

// 1. Scan Examples/ for all .json files
const files = fs.readdirSync(examplesDir)
  .filter(f => f.endsWith('.json'))
  .sort();

// 2. Read and parse each example
const examples = [];
for (const file of files) {
  try {
    const data = JSON.parse(fs.readFileSync(path.join(examplesDir, file), 'utf8'));
    examples.push(data);
  } catch (e) {
    console.warn('Skipping ' + file + ': ' + e.message);
  }
}

// 3. Write js/examples-data.js
const js = '// Auto-generated by scripts/build-examples-data.js — do not edit manually\n' +
           '// Run build-examples.bat to regenerate\n' +
           'window.EXAMPLE_SKETCHES = ' + JSON.stringify(examples, null, 2) + ';\n';

fs.writeFileSync(outPath, js, 'utf8');

const sizeKB = (Buffer.byteLength(js, 'utf8') / 1024).toFixed(1);
console.log('Generated js/examples-data.js with ' + examples.length + ' examples (' + sizeKB + ' KB)');
